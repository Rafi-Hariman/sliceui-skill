// mining-exclusion — generated-by-SliceUI sources cannot inflate their own recipe confidence.
import { test } from "node:test";
import assert from "node:assert/strict";
import { mineProjectDeclarations, aggregateObservations, declarationsFromAggregates, listProjectScss } from "../../src/project/scss-mine.mjs";
import { mkdtempSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const GEN = (n) => `// Generated by SliceUI\n::ng-deep .search-options input { width: ${n}px; }`;
const REAL = (n) => `::ng-deep .search-options input { width: ${n}px; }`;

async function widthSemantics(files, includeGenerated = false) {
  const { observations } = await mineProjectDeclarations("/x", { files, includeGenerated });
  const { aggregates } = aggregateObservations(observations);
  const d = declarationsFromAggregates(aggregates).find((x) => x.selector === "search-options input" && x.property === "width");
  return d;
}

test("mining-exclusion: a generated file is excluded from recipe-confidence by default", async () => {
  // 2 real components + 1 generated copy: the generated file must NOT make this 3 usages.
  const files = [
    { path: "/x/a.component.scss", src: REAL(384) },
    { path: "/x/b.component.scss", src: REAL(384) },
    { path: "/x/gen.component.scss", src: GEN(384) },
  ];
  const d = await widthSemantics(files);
  assert.equal(d.values.length, 1, "the generated copy's value is not mined by default");
  assert.equal(d.semantics, "UNVERIFIED_SAMPLE", "2 usages cannot promote; the generated file did not inflate to 3");
});

test("mining-exclusion: three REAL components promote; a generated copy still adds nothing", async () => {
  const files = [
    { path: "/x/a.component.scss", src: REAL(384) },
    { path: "/x/b.component.scss", src: REAL(384) },
    { path: "/x/c.component.scss", src: REAL(384) },
    { path: "/x/gen.component.scss", src: GEN(384) },
  ];
  const d = await widthSemantics(files);
  assert.equal(d.semantics, "DESIGN_OVERRIDABLE", "3 genuine usages promote");
  assert.equal(d.confidence, 0.9, "confidence from the 3 real usages, not 4");
});

test("mining-exclusion: explicit approval (includeGenerated) is the only inclusion mechanism", async () => {
  const files = [
    { path: "/x/a.component.scss", src: REAL(384) },
    { path: "/x/b.component.scss", src: REAL(384) },
    { path: "/x/gen.component.scss", src: GEN(384) },
  ];
  const approved = await widthSemantics(files, true);
  assert.equal(approved.values.length >= 1, true, "with approval the generated value is mined");
});

test("mining-exclusion: listProjectScss never lists a generated source", () => {
  const dir = mkdtempSync(join(tmpdir(), "sliceui-mine-"));
  mkdirSync(join(dir, "app"), { recursive: true });
  writeFileSync(join(dir, "app", "real.component.scss"), REAL(384));
  writeFileSync(join(dir, "app", "gen.component.scss"), GEN(384));
  const listed = listProjectScss(dir).map((f) => f.path.split("/").pop());
  assert.ok(listed.includes("real.component.scss"));
  assert.ok(!listed.includes("gen.component.scss"), "generated source excluded from the file listing");
});
