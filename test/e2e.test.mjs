// E2E — proves the core promise WITHOUT an API key or real project:
// detectProject (Angular 13 fixture) → transcribeStatic (synthetic screenshot)
// → buildCodegenPrompt → assert the generated-prompt content carries Angular 13 idioms.
// This is the automated half of the E2E gate; the manual half runs in a real Angular
// project (bill) and ends in `ng build`.

import { test } from "node:test";
import assert from "node:assert/strict";
import { writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { dirname } from "node:path";
import { detectProject } from "../src/commands/detect.mjs";
import { transcribeStatic } from "../src/commands/transcribe-static.mjs";
import { buildCodegenPrompt } from "../src/lib/prompt-rules/output-rules.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const FIX = join(HERE, "fixtures", "angular13");

/** Build a structured BMP fixture: dark background + a white nav band + white hero band. */
function makeBmp(path, width, height) {
  const stride = Math.ceil((width * 24) / 32) * 4;
  const dataSize = stride * height;
  const buf = Buffer.alloc(54 + dataSize);
  buf.write("BM", 0, "ascii");
  buf.writeUInt32LE(54 + dataSize, 2);
  buf.writeUInt32LE(54, 10);
  buf.writeUInt32LE(40, 14);
  buf.writeInt32LE(width, 18);
  buf.writeInt32LE(height, 22);
  buf.writeUInt16LE(1, 26);
  buf.writeUInt16LE(24, 28);
  buf.writeUInt32LE(0, 30);
  buf.writeUInt32LE(dataSize, 34);
  const setPx = (x, y, r, g, b) => {
    const srcRow = height - 1 - y;
    const d = 54 + srcRow * stride + x * 3;
    buf[d] = b; buf[d + 1] = g; buf[d + 2] = r;
  };
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      setPx(x, y, 15, 23, 42); // dark bg #0f172a
    }
  }
  // nav band (white, top 20%)
  for (let y = 0; y < height * 0.18; y++) for (let x = 0; x < width; x++) setPx(x, y, 255, 255, 255);
  // hero band (white, middle)
  for (let y = height * 0.4; y < height * 0.6; y++) for (let x = 0; x < width; x++) setPx(x, y, 255, 255, 255);
  writeFileSync(path, buf);
}

test("E2E: detect → transcribe → codegen prompt carries Angular 13 idioms", async () => {
  // 1. detect
  const ctx = await detectProject(FIX);
  assert.equal(ctx.framework.id, "angular");
  assert.equal(ctx.framework.versionMajor, 13);
  assert.equal(ctx.prefix, "app");

  // 2. transcribe a synthetic screenshot (static tier — no key needed)
  const img = join(mkdtempSync(join(tmpdir(), "sliceui-e2e-")), "hero.png");
  makeBmp(img, 200, 120);
  const tr = transcribeStatic(img);
  rmSync(img, { recursive: true, force: true });
  assert.equal(tr.ok, true, tr.reason);
  assert.ok(tr.transcript.layout.length > 0, "transcript has layout");

  // 3. codegen prompt from project context + transcript
  const prompt = buildCodegenPrompt({ transcript: tr.transcript, projectContext: ctx });

  // 4. assert the prompt carries Angular 13 idioms + project adaptation
  assert.ok(prompt.includes("FRAMEWORK: Angular 13"), "prompt names Angular 13");
  assert.ok(prompt.includes("<project_context>"), "project context block present");
  assert.ok(prompt.includes("selector: '<prefix>-<name>'"), "selector rule present");
  assert.ok(prompt.includes("constructor(private"), "constructor DI rule present");
  assert.ok(prompt.includes("*ngIf") && prompt.includes("*ngFor"), "*ngIf/*ngFor rules present");
  assert.ok(prompt.includes("NO standalone") || prompt.includes("NOT standalone"), "standalone guard present");
  assert.ok(prompt.includes("NO inject()") || prompt.includes("NOT inject()"), "inject() guard present");
  assert.ok(prompt.includes("// Generated by SliceUI"), "output marker present");
});

test("E2E: codegen prompt injects the pilar catalog pointer for UII projects", () => {
  // A project that fingerprints UII (profile 'uii') must be told to read the pilar reference +
  // showcase — the org-private component playbook — before emitting uii-* tags.
  const ctx = { framework: { id: "angular", label: "Angular", versionMajor: 13 }, profile: "uii", prefix: "ugw", componentDir: "src/app" };
  const prompt = buildCodegenPrompt({ transcript: { meta: { image: "x.xml" }, layout: [] }, projectContext: ctx });

  assert.match(prompt, /pilar-reference\.md/, "prompt points at pilar-reference.md");
  assert.match(prompt, /pilar-showcase\.md/, "prompt points at pilar-showcase.md");
  assert.match(prompt, /Read TARGETED, never full-file/, "prompt guards against full-file context burn");
});

test("E2E: codegen prompt omits the pilar pointer for a generic (non-UII) project", () => {
  const ctx = { framework: { id: "angular", label: "Angular", versionMajor: 13 }, profile: "generic", prefix: "app", componentDir: "src/app" };
  const prompt = buildCodegenPrompt({ transcript: { meta: { image: "x.xml" }, layout: [] }, projectContext: ctx });

  assert.ok(!prompt.includes("pilar-reference.md"), "generic project must not receive the pilar pointer");
  assert.ok(!prompt.includes("pilar-showcase.md"), "generic project must not receive the showcase pointer");
});

test("E2E: degraded transcript is flagged when text is unreadable", () => {
  // simulate non-OCR static output → textQuality "unreadable"
  const img = join(mkdtempSync(join(tmpdir(), "sliceui-e2e-")), "hero.png");
  makeBmp(img, 200, 120);
  const tr = transcribeStatic(img);
  rmSync(img, { recursive: true, force: true });
  // On macOS OCR usually succeeds, so we only assert the flag is consistent with meta
  assert.equal(tr.ok, true);
  assert.ok(["ocr", "unreadable"].includes(tr.transcript.meta.textQuality), "textQuality is ocr or unreadable");
});
