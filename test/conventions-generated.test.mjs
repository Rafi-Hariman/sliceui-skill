import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { extractConventions } from "../src/framework/angular/conventions.mjs";

test("C5: init does not absorb a SliceUI-generated file into the ::ng-deep corpus", () => {
  const root = mkdtempSync(join(tmpdir(), "sliceui-c5-"));
  try {
    mkdirSync(join(root, "src"), { recursive: true });
    // Project's own convention.
    writeFileSync(join(root, "src", "project.component.scss"), "::ng-deep .gateway-table { border-radius: 6px; }\n");
    // A file SliceUI itself generated (its first line is the output marker).
    writeFileSync(join(root, "src", "sliced.component.scss"), "// Generated by SliceUI\n::ng-deep .invented-by-me { color: #f00; }\n");

    const c = extractConventions(root, { prefix: "app" });
    const selectors = c.ngDeepCorpus.map((x) => x.selector);
    assert.ok(selectors.some((s) => s.includes("gateway-table")), "project convention is kept");
    assert.ok(!selectors.some((s) => s.includes("invented-by-me")), "SliceUI-generated block is excluded");
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("F10: classVocabulary tags defined vs undefined classes", () => {
  const root = mkdtempSync(join(tmpdir(), "sliceui-f10-"));
  try {
    mkdirSync(join(root, "src"), { recursive: true });
    writeFileSync(join(root, "src", "a.component.html"), `<div class="well button-action-center"></div>`);
    // `.well` has a top-level definition; `button-action-center` is only ever nested under modal-footer.
    writeFileSync(
      join(root, "src", "a.component.scss"),
      ".well { border: 1px solid #eee; }\n.modal-footer { .button-action-center { display: flex; justify-content: center; } }\n",
    );
    const c = extractConventions(root, { prefix: "app" });
    const well = c.classVocabulary.find((x) => x.name === "well");
    const bac = c.classVocabulary.find((x) => x.name === "button-action-center");
    assert.equal(well.definition, "defined", ".well is a top-level rule");
    assert.equal(bac.definition, "context-dependent", "button-action-center only exists nested under .modal-footer");
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("F10: classVocabulary marks a name with NO css as undefined", () => {
  const root = mkdtempSync(join(tmpdir(), "sliceui-f10b-"));
  try {
    mkdirSync(join(root, "src"), { recursive: true });
    writeFileSync(join(root, "src", "a.component.html"), `<div class="ghost-name"></div>`);
    writeFileSync(join(root, "src", "a.component.scss"), `.real { color: red; }`);
    const c = extractConventions(root, { prefix: "app" });
    const ghost = c.classVocabulary.find((x) => x.name === "ghost-name");
    assert.equal(ghost.definition, "undefined", "name with no CSS is a name-trap");
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("F5: corpus blocks are stored hash-free (no [_ngcontent-*] leak into copy-targets)", () => {
  const root = mkdtempSync(join(tmpdir(), "sliceui-f5-"));
  try {
    mkdirSync(join(root, "src"), { recursive: true });
    // A compiled-source SCSS leak: selector + block carry Angular scope attributes.
    writeFileSync(
      join(root, "src", "leaked.component.scss"),
      ".filter-options[_ngcontent-art-c12] .search-input[_ngcontent-art-c12] { border: 1px solid #b1bccc; }\n",
    );
    const c = extractConventions(root, { prefix: "app" });
    for (const entry of c.ngDeepCorpus) {
      assert.ok(!/\[_(?:ngcontent|nhost)-[^\]]*\]/.test(entry.block ?? ""), `block must be hash-free: ${entry.selector}`);
      assert.ok(!/\[_(?:ngcontent|nhost)-[^\]]*\]/.test(entry.selector ?? ""), `selector must be hash-free: ${entry.selector}`);
    }
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
