// Output rules + prompt assembler for the local skill's code-gen step.
// Philosophy ported from the SliceUI web app src/lib/prompts.ts (buildPrompt):
// code-only response, self-contained component, exact visible text as placeholder,
// gray-div images, icon comments, exact hex colors, mandatory SliceUI first line.

import { getFrameworkRules } from "./frameworks.mjs";

/**
 * Assemble the full code-generation prompt from a validated transcript + project context.
 *
 * @param {object} opts
 * @param {object} opts.transcript     — validated transcript (see transcript-schema.mjs)
 * @param {object} opts.projectContext — detect output (.sliceui/project-context.json)
 * @param {string} [opts.instructions] — free-form user instructions
 * @returns {string}
 */
export function buildCodegenPrompt({ transcript, projectContext, instructions }) {
  const pc = projectContext ?? {};
  const fw = pc.framework ?? {};
  const fwId = fw.id ?? "unknown";
  const fwVersion = fw.versionMajor ? ` ${fw.versionMajor}` : "";
  const fwLabel = `${fw.label ?? fwId}${fwVersion}`;

  const blocks = [];

  blocks.push(`You are a senior frontend engineer working INSIDE the user's project. Generate production-ready component code that matches this project's conventions exactly, based on the UI transcript below (transcribed from a screenshot).`);

  // --- project context (highest priority) ---
  blocks.push(`## Project context
If the project context conflicts with other instructions, prioritize the project context — the code must drop into THIS codebase.

<project_context>
${JSON.stringify(pc, null, 2)}
</project_context>`);

  // --- transcript ---
  blocks.push(`## UI transcript (from screenshot ${transcript?.meta?.image ?? "?"})
<transcript>
${JSON.stringify(transcript, null, 2)}
</transcript>`);

  // --- framework rules ---
  const rules = getFrameworkRules(fwId);
  if (rules) {
    blocks.push(`## Framework rules
FRAMEWORK: ${fwLabel}

${rules}`);
  }

  // --- critical output rules ---
  blocks.push(`CRITICAL OUTPUT RULES:
1. Write real files into the project (use the componentDir and naming conventions from project_context).
2. First line of each generated file: // Generated by SliceUI (or <!-- Generated by SliceUI --> for html/scss).
3. Use the exact text from the transcript as content. When text is unreadable/placeholder, use plausible copy and tell the user which strings you invented.
4. For images: gray placeholder div with descriptive alt text.
5. For icons: a comment /* icon: {description} */ as placeholder.
6. Match colors from the transcript exactly using hex values — unless project tokens exist for them (then use the tokens).
7. Self-contained component — not a full app. No html/body/main entry points.
8. After writing, run the project's build or type-check if available and fix errors you introduced.`);

  // --- instructions ---
  if (instructions?.trim()) {
    blocks.push(`## Additional instructions
${instructions.trim()}`);
  }

  return blocks.join("\n\n");
}
