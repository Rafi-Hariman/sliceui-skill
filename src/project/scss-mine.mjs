// scss-mine — declaration-level mining of project SCSS → observations → aggregation.
//
// This is the REAL production path for Prompt B. It parses SCSS with the `sass` compiler (lazy-
// imported, a devDependency the same way render-mount/render-verify use it) so nested selectors,
// at-rules, `:host`, and `::ng-deep` are flattened correctly — never a regex-only parser. The flat
// CSS is then read with a balanced-brace scanner into per-declaration observations, which are
// aggregated by a SEMANTIC key (family + role + selector + property + state + media), with
// independent-usage counting so duplicates within one component/file family never inflate confidence.
//
// Value normalization is conservative: colors canonicalized, zero-unit/decimal normalized,
// !important extracted — but px/rem/%/vw are NEVER equated without environment evidence.

import fg from "fast-glob";
import { readFileSync } from "node:fs";
import { join, basename } from "node:path";
import { familyForSelector, LIBRARY_INTERNAL, LIBRARY_INTERNAL_WRAPPER_GUARD } from "../framework/angular/conventions.mjs";
import { classifyDeclaration } from "./recipe-semantics.mjs";

const SKIP = ["**/node_modules/**", "**/dist/**", "**/.angular/**", "**/build/**", "**/.sliceui/**"];

// ---------------------------------------------------------------------------
// ingestion
// ---------------------------------------------------------------------------

/** List a project's SCSS files (paths + contents), skipping generated/vendor noise. */
export function listProjectScss(root, read = readFileSync) {
  const files = fg.sync(["**/*.scss", "**/*.css"], { cwd: root, ignore: SKIP, absolute: true });
  return files
    .filter((p) => !isSliceUiGenerated(read(p, "utf8")))
    .sort()
    .map((p) => ({ path: p, src: read(p, "utf8") }));
}

function isSliceUiGenerated(src) {
  return /^\s*(?:\/\/|<!--)\s*Generated by SliceUI/.test(String(src ?? ""));
}

/**
 * Mine SCSS sources into per-declaration observations.
 * @param {string} root — project root (for relative provenance)
 * @param {{ files?: Array<{path:string, src:string}> }} [opts]
 * @returns {Promise<{ observations: Array, parseFailures: Array, stats: object }>}
 */
export async function mineProjectDeclarations(root, opts = {}) {
  // Generated-by-SliceUI sources are excluded from confidence calculation BY DEFAULT — a slice's own
  // output must never recursively increase its recipe confidence. Explicit approval
  // (`includeGenerated: true`) is the only way to mine them.
  const raw = opts.files ?? listProjectScss(root);
  const files = (opts.includeGenerated === true ? raw : raw.filter((f) => !isSliceUiGenerated(f.src)))
    .slice().sort((a, b) => String(a.path).localeCompare(String(b.path)));
  let sassLib = null;
  try {
    sassLib = await import("sass");
  } catch { /* sass unavailable (public install) — degrade to salvage, never throw */ }

  const observations = [];
  const parseFailures = [];

  for (const f of files) {
    let rules = null;
    if (sassLib) {
      try {
        const out = sassLib.compileString(f.src, { style: "expanded" });
        rules = readFlatRules(out.css);
      } catch (err) {
        parseFailures.push({ file: rel(root, f.path), message: String(err?.message ?? err).slice(0, 240) });
      }
    }
    if (!rules) rules = salvageNgDeepRules(f.src); // degraded: failure already recorded, salvage the ::ng-deep corpus

    for (const rule of rules) {
      for (const d of rule.declarations) {
        observations.push(observationOf(root, f, rule, d));
      }
    }
  }

  return { observations, parseFailures, stats: miningStats(files, observations, parseFailures) };
}

// ---------------------------------------------------------------------------
// flat CSS reading (input is already flattened by sass — no nesting, only @media)
// ---------------------------------------------------------------------------

/** Read flat CSS into `[{ selector, media, declarations: [{property,value,important}] }]`. */
export function readFlatRules(css) {
  const out = [];
  const stack = []; // media contexts
  let i = 0;
  const n = css.length;
  while (i < n) {
    const ch = css[i];
    if (/\s/.test(ch)) { i++; continue; }
    if (ch === "@") {
      const at = readAtRule(css, i);
      if (!at) break;
      if (at.name === "media" || at.name === "supports") {
        stack.push(at.name === "media" ? at.prelude : `@supports ${at.prelude}`);
        i = at.bodyStart;
        continue;
      }
      if (at.name === "keyframes" || at.name === "-webkit-keyframes") {
        i = at.bodyEnd + 1; // skip keyframes body entirely
        continue;
      }
      // other at-rules (@font-face, @import, @charset): skip the rule
      i = at.bodyEnd >= 0 ? at.bodyEnd + 1 : at.end + 1;
      continue;
    }
    if (ch === "}") {
      stack.pop();
      i++;
      continue;
    }
    // a selector rule
    const selEnd = css.indexOf("{", i);
    if (selEnd === -1) break;
    const selector = css.slice(i, selEnd).trim();
    const body = readBlock(css, selEnd);
    if (body) {
      out.push({ selector, media: stack[stack.length - 1] ?? null, declarations: parseDeclarations(body.body) });
      i = body.end + 1;
    } else break;
  }
  return out;
}

function readAtRule(css, i) {
  const m = /^@([\w-]+)/.exec(css.slice(i));
  if (!m) return null;
  const name = m[1];
  const brace = css.indexOf("{", i);
  if (brace === -1) {
    // at-rule without a block (@import ...;)
    const semi = css.indexOf(";", i);
    return { name, prelude: css.slice(i + name.length + 1, semi).trim(), bodyStart: -1, bodyEnd: -1, end: semi === -1 ? css.length : semi };
  }
  const prelude = css.slice(i + name.length + 1, brace).trim();
  const body = readBlock(css, brace);
  return { name, prelude, bodyStart: brace + 1, bodyEnd: body ? body.end : brace, end: body ? body.end : brace };
}

/** Balanced-brace body reader. Returns `{ body, end }` (end = index of the matching `}`). */
function readBlock(css, openBrace) {
  let depth = 0;
  for (let i = openBrace; i < css.length; i++) {
    const c = css[i];
    if (c === "{") depth++;
    else if (c === "}") {
      depth--;
      if (depth === 0) return { body: css.slice(openBrace + 1, i), end: i };
    }
  }
  return null;
}

/** Flat declaration parse: `property: value [!important]` lines (post-sass, no nesting). */
export function parseDeclarations(body) {
  const out = [];
  for (const raw of String(body ?? "").split(";")) {
    const d = raw.trim();
    if (!d) continue;
    const ci = d.indexOf(":");
    if (ci < 0) continue;
    const property = d.slice(0, ci).trim();
    let value = d.slice(ci + 1).trim();
    const important = /!important\s*$/i.test(value);
    if (important) value = value.replace(/!important\s*$/i, "").trim();
    if (!property || !value) continue;
    out.push({ property, value, important });
  }
  return out;
}

/** Degraded path: on sass failure, salvage the file's ::ng-deep blocks via the legacy scanner. */
function salvageNgDeepRules(src) {
  // A balanced-brace scan of top-level `::ng-deep`/`:host ::ng-deep` rules (the corpus subset).
  const out = [];
  const re = /::ng-deep/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    const open = src.indexOf("{", m.index);
    if (open === -1) continue;
    const block = readBlock(src, open);
    if (!block) continue;
    // Find the start of the selector (walk back to the previous `}` or start).
    let selStart = m.index;
    while (selStart > 0 && src[selStart - 1] !== "}") selStart--;
    const selector = src.slice(selStart, open).replace(/\s+/g, " ").trim();
    if (selector) out.push({ selector, media: null, declarations: parseDeclarations(block.body) });
  }
  return out;
}

// ---------------------------------------------------------------------------
// observation construction
// ---------------------------------------------------------------------------

function observationOf(root, file, rule, decl) {
  const selector = normalizeSelector(rule.selector);
  const family = familyForSelector(selector);
  return {
    sourceFile: rel(root, file.path),
    component: componentIdentity(file.path),
    selector,
    family: family ?? null,
    role: roleOf(selector),
    inNgDeep: /::ng-deep/.test(rule.selector),
    libraryInternal: libraryInternalOf(selector, family),
    pseudoState: stateOf(selector),
    media: rule.media ?? null,
    property: decl.property.toLowerCase(),
    value: normalizeValue(decl.value, decl.property),
    important: decl.important,
    provenance: { file: rel(root, file.path), selector },
  };
}

/** Component/file identity: the owning component name (dedups hope/slice copies, responsive variants). */
export function componentIdentity(path) {
  return basename(path)
    .replace(/\.component\.(scss|css)$/i, "")
    .replace(/\.(scss|css)$/i, "")
    .replace(/^_/, "");
}

/** Loose selector normalization: strip hashed scopes + :host/::ng-deep prefixes + the leading `.`
 *  (so `.form-control` matches the `^form-control$` family/library-internal maps), collapse whitespace. */
export function normalizeSelector(sel) {
  return String(sel ?? "")
    .replace(/\[_(?:ngcontent|nghost)-[^\]]*\]/g, "")
    .replace(/^(?::host\s+)?::ng-deep\s*/i, "")
    .replace(/::ng-deep\s*/gi, " ")
    .replace(/^\./, "")
    .replace(/\s+/g, " ")
    .trim();
}

/** Whether the selector targets known library-internal DOM (reuses conventions' single map). */
function libraryInternalOf(selector, family) {
  if (!family) return false;
  const rx = LIBRARY_INTERNAL[family];
  if (!rx || !rx.test(selector)) return false;
  const guard = LIBRARY_INTERNAL_WRAPPER_GUARD[family];
  return guard ? !guard.test(selector) : true;
}

/** A coarse selector role, for the aggregation key + the portal/overlay/fill counterexamples. */
export function roleOf(selector) {
  const s = String(selector ?? "").toLowerCase();
  if (/pagination|page-box|table-footer|limit-options/.test(s)) return "pagination";
  if (/search|pencarian|filter-options/.test(s)) return "search";
  if (/portal|cdk-overlay|dropdown-menu|overlay-content|cdk-connected/.test(s)) return "portal";
  if (/badge|toast|floating|notification|notif/.test(s)) return "overlay";
  if (/gateway-table|table-|cell-html|empty-data/.test(s)) return "table";
  if (/form-control|ngx-select|^input$/.test(s)) return "form";
  return null;
}

/** The state signal in a selector (`:hover`/`:focus`/… or an `_active`/`.active`/`.selected` token). */
export function stateOf(selector) {
  const s = String(selector ?? "");
  const m = /:(hover|focus|active|visited|disabled|checked|focus-within|focus-visible|selected)\b/i.exec(s);
  if (m) return m[1].toLowerCase();
  if (/(^|[._-])(active|selected|disabled)\b/i.test(s)) return /(active|selected|disabled)\b/i.exec(s)[1].toLowerCase();
  return null;
}

// ---------------------------------------------------------------------------
// value normalization (conservative)
// ---------------------------------------------------------------------------

export function normalizeValue(raw, property = "") {
  let v = String(raw ?? "").trim();
  v = v.replace(/!important\s*$/i, "").trim();
  // rgba/rgb → hex (opaque only; alpha != 1 is left as-is, never silently dropped).
  v = v.replace(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*(1|1\.0+)\s*)?\)/gi, (_m, r, g, b) => rgbToHex(r, g, b));
  // #abc → #aabbcc (case-normalized).
  v = v.replace(/#([0-9a-f])([0-9a-f])([0-9a-f])\b/gi, (m2, r, g, b) => `#${r}${r}${g}${g}${b}${b}`.toLowerCase());
  v = v.toLowerCase();
  // Per-token: zero-unit + decimal normalization. Units are NEVER cross-converted.
  v = v.split(/(\s+)/).map((tok) => (/\s/.test(tok) ? tok : normalizeToken(tok))).join("");
  // border-radius: 4 identical values → 1 (safely comparable with a uniform longhand/short).
  if (/^border(-(top|right|bottom|left))?-radius$/.test(property)) {
    const parts = v.split(/\s+/);
    if (parts.length === 4 && parts.every((p) => p === parts[0])) v = parts[0];
  }
  return v;
}

function normalizeToken(tok) {
  const m = /^([+-]?)(\d+(?:\.\d+)?|\.\d+)([a-z%]*)$/i.exec(tok);
  if (!m) return tok;
  const sign = m[1];
  const unit = m[3].toLowerCase();
  const n = Number(m[2]);
  if (n === 0) return "0";
  return sign + String(parseFloat(n.toFixed(4))) + unit;
}

function rgbToHex(r, g, b) {
  const h = (x) => Number(x).toString(16).padStart(2, "0");
  return `#${h(r)}${h(g)}${h(b)}`;
}

// ---------------------------------------------------------------------------
// aggregation (semantic key + independent-usage counting)
// ---------------------------------------------------------------------------

/** Aggregate observations by a semantic declaration key. */
export function aggregateObservations(observations = []) {
  const byKey = new Map();
  for (const o of observations) {
    const key = [o.family ?? "", o.role ?? "", o.selector, o.property, o.pseudoState ?? "", o.media ?? ""].join("|");
    let agg = byKey.get(key);
    if (!agg) {
      agg = {
        key,
        family: o.family,
        role: o.role,
        selector: o.selector,
        property: o.property,
        pseudoState: o.pseudoState,
        media: o.media,
        inNgDeep: o.inNgDeep,
        libraryInternal: o.libraryInternal,
        valueGroups: new Map(), // value -> Set<component>
        components: new Set(),
        occurrences: 0,
        provenance: [],
      };
      byKey.set(key, agg);
    }
    const comp = o.component;
    agg.components.add(comp);
    if (!agg.valueGroups.has(o.value)) agg.valueGroups.set(o.value, new Set());
    agg.valueGroups.get(o.value).add(comp);
    agg.occurrences += 1;
    if (agg.provenance.length < 12 && !agg.provenance.some((p) => p.file === o.sourceFile && p.value === o.value)) {
      agg.provenance.push({ file: o.sourceFile, selector: o.selector, value: o.value, important: o.important, media: o.media });
    }
  }

  const aggregates = [...byKey.values()]
    .map((a) => ({
      key: a.key,
      family: a.family,
      role: a.role,
      selector: a.selector,
      property: a.property,
      pseudoState: a.pseudoState,
      media: a.media,
      inNgDeep: a.inNgDeep,
      libraryInternal: a.libraryInternal,
      values: [...a.valueGroups.keys()],
      valueComponents: [...a.valueGroups.entries()].map(([v, comps]) => ({ value: v, components: [...comps] })),
      independentUsageCount: a.components.size,
      hasVariance: a.valueGroups.size > 1 && a.components.size >= 2,
      occurrences: a.occurrences,
      provenance: a.provenance,
    }))
    .sort((a, b) => a.key.localeCompare(b.key));

  return { aggregates };
}

/** Classify every aggregate into a declaration with semantics + confidence. */
export function declarationsFromAggregates(aggregates = []) {
  return aggregates.map((a) => {
    const dominant = a.valueComponents.slice().sort((x, y) => y.components.length - x.components.length)[0];
    const decl = classifyDeclaration(
      { property: a.property, value: dominant?.value ?? a.values[0], important: false },
      {
        usageCount: a.independentUsageCount,
        hasVariance: a.hasVariance,
        selector: a.selector,
        family: a.family ?? "",
        libraryInternal: a.libraryInternal,
        role: a.role,
        media: a.media,
        statePseudo: a.pseudoState,
      },
    );
    return { selector: a.selector, family: a.family, role: a.role, property: a.property, media: a.media, pseudoState: a.pseudoState, values: a.values, provenance: a.provenance, ...decl };
  });
}

/** Count classified declarations by semantics + confidence band (for the report). */
export function declarationsStats(declarations = []) {
  const bySemantics = {};
  const byConfidenceBand = { high: 0, medium: 0, low: 0, unverified: 0 };
  for (const d of declarations) {
    bySemantics[d.semantics] = (bySemantics[d.semantics] ?? 0) + 1;
    if (d.confidence >= 0.85) byConfidenceBand.high++;
    else if (d.confidence >= 0.65) byConfidenceBand.medium++;
    else if (d.confidence >= 0.45) byConfidenceBand.low++;
    else byConfidenceBand.unverified++;
  }
  return { declarationCount: declarations.length, bySemantics, byConfidenceBand };
}

function miningStats(files, observations, parseFailures) {
  return {
    filesScanned: files.length,
    components: new Set(observations.map((o) => o.component)).size,
    declarationsMined: observations.length,
    parseFailures: parseFailures.length,
  };
}

function rel(root, abs) {
  const r = abs.startsWith(root) ? abs.slice(root.length) : abs;
  return r.replace(/^[/\\]/, "");
}

/**
 * Attach mined declaration observations to a conventions object (for `init`/`detect` to persist
 * into conventions.json). Angular projects only — the ::ng-deep/role grammar is Angular-shaped.
 * Never throws: a mining failure degrades to `declarations: null` + a diagnostic, never blocks init.
 */
export async function withMinedDeclarations(root, conventions, frameworkId = "angular") {
  if (frameworkId !== "angular") return conventions;
  try {
    const { observations, parseFailures, stats } = await mineProjectDeclarations(root);
    const { aggregates } = aggregateObservations(observations);
    return { ...conventions, declarations: { aggregates, parseFailures, stats } };
  } catch (err) {
    return { ...conventions, declarations: null, miningDiagnostic: String(err?.message ?? err).slice(0, 200) };
  }
}
