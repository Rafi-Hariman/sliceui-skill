// conventions — mine a Vue project for "HOW this team writes" and emit deterministic facts.
// Vue-native counterpart of framework/angular/conventions.mjs. The Angular miner's idiom does
// NOT transfer: Vue scoped styles use :deep(selector) (not ::ng-deep), templates use
// @event/v-model (not (click)="handler()"), and components are SFCs (not NgModule declarations).
//
// Same contract, different shape — "target not equal" (plan §2). Vue emits its own keys
// (deepCorpus, not ngDeepCorpus) so the Angular-shaped resolve/referee consumers never mis-read
// a Vue corpus as a ::ng-deep corpus. Zero new dependencies: fast-glob + readFileSync + regex.

import fg from "fast-glob";
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const SKIP = ["**/node_modules/**", "**/dist/**", "**/.angular/**", "**/build/**", "**/.sliceui/**", "**/.nuxt/**"];

// Bootstrap-grid + generic layout classes that carry no project-specific reuse meaning. A Vue
// project's class vocabulary is the PROJECT's own classes (filter-card, btn-search,
// label-custom-*), never the framework's utility layer — Tailwind utilities are excluded
// upstream (see detectTailwind), not here.
const TRIVIAL_CLASS = /^(row|container(-fluid)?|col(-(xs|sm|md|lg|xl|xxl))?(-\d+)?|text-(left|right|center|justify)|pull-(left|right)|hidden(-[a-z]+)?|clearfix|flex|grid|block|inline-block|relative|absolute|fixed|sticky)$/;

export function extractConventions(root, ctx = {}) {
  const vueFiles = fg.sync(["**/*.vue"], { cwd: root, ignore: SKIP, absolute: true });
  const styleFiles = fg.sync(["**/*.scss", "**/*.css", "**/*.less"], { cwd: root, ignore: SKIP, absolute: true });

  const files = vueFiles.map((p) => ({ path: p, src: readFileSyncSafe(p) }));
  const projectFiles = files.filter((f) => !isSliceUiGenerated(f.src));
  const styleSrcs = styleFiles.map((p) => ({ path: p, src: readFileSyncSafe(p) })).filter((f) => !isSliceUiGenerated(f.src));

  // Tailwind is a utility layer, not a reusable-class vocabulary. When present, classVocabulary
  // stays empty on purpose — composing utilities is the codegen rule, not "reuse these classes".
  const tailwind = detectTailwind(root, styleSrcs, projectFiles);

  const classVocabulary = tailwind ? [] : extractClassVocabulary(projectFiles);
  const deepCorpus = extractDeepCorpus(projectFiles);
  const componentAnatomy = extractAnatomy(projectFiles, tailwind);
  const naming = extractNaming(projectFiles);

  return { classVocabulary, deepCorpus, componentAnatomy, naming };
}

/** A file whose first line carries the SliceUI marker is our own prior output, not a convention. */
function isSliceUiGenerated(src) {
  return /^\s*(?:\/\/|<!--)\s*Generated by SliceUI/.test(String(src ?? ""));
}

// ---------- Tailwind detection ----------

/** Tailwind present when the package depends on it, a tailwind.config.* exists, or a stylesheet
 *  carries the Tailwind entry (@import "tailwindcss", @tailwind base, or v4 @theme). */
function detectTailwind(root, styleSrcs, vueFiles) {
  let pkg = null;
  try { pkg = JSON.parse(readFileSyncSafe(join(root, "package.json")) || "{}"); } catch { pkg = {}; }
  const deps = { ...(pkg.dependencies ?? {}), ...(pkg.devDependencies ?? {}) };
  if (deps.tailwindcss) return true;
  try {
    if (existsSync(join(root, "tailwind.config.js")) || existsSync(join(root, "tailwind.config.ts"))) return true;
  } catch { /* ignore */ }
  const all = [...styleSrcs.map((f) => f.src), ...vueFiles.map((f) => extractStyles(f.src).map((s) => s.body)).flat()];
  return /@import\s+["']tailwindcss|@tailwind\s+(base|components|utilities)|@theme\b/.test(all.join("\n"));
}

// ---------- SFC section extraction ----------

/** Pull the first `<template>…</template>` body. */
function extractTemplate(src) {
  return /<template\b[^>]*>([\s\S]*?)<\/template>/.exec(src)?.[1] ?? "";
}

/** Pull every `<style …>…</style>` block as { attrs, body }. */
function extractStyles(src) {
  const out = [];
  for (const m of src.matchAll(/<style\b([^>]*)>([\s\S]*?)<\/style>/g)) {
    out.push({ attrs: m[1], body: m[2] });
  }
  return out;
}

// ---------- class vocabulary ----------

/** Count static class="…" usage across templates. Vue's dynamic :class / v-bind:class is
 *  excluded via the negative lookbehind (a `class="…"` inside `:class="…"` is a binding, not a
 *  literal reuse target). Split on whitespace, skip layout/utility noise + interpolation. */
function extractClassVocabulary(files) {
  const counts = new Map();
  for (const f of files) {
    const tpl = extractTemplate(f.src);
    for (const m of tpl.matchAll(/(?<!:)class\s*=\s*["']([^"']+)["']/g)) {
      for (const raw of m[1].split(/\s+/)) {
        const cls = raw.trim();
        if (!cls || TRIVIAL_CLASS.test(cls)) continue;
        if (/[[\]{}(){}]/.test(cls)) continue; // :class object/array leftovers, {{ }} interpolation
        counts.set(cls, (counts.get(cls) ?? 0) + 1);
      }
    }
  }

  const entries = [...counts.entries()].sort((a, b) => b[1] - a[1]);
  const families = new Map();
  for (const [cls] of entries) {
    const fam = familyOf(cls);
    if (fam) families.set(fam, (families.get(fam) ?? 0) + 1);
  }
  const top = entries.slice(0, 40).map(([name, count]) => ({ name, count }));
  const taxonomy = entries
    .filter(([cls]) => {
      const fam = familyOf(cls);
      return fam && (families.get(fam) ?? 0) >= 2;
    })
    .map(([name, count]) => ({ name, count }));

  const merged = new Map();
  for (const item of [...top, ...taxonomy]) merged.set(item.name, item);

  return [...merged.values()].map(({ name, count }) => ({
    name,
    count,
    family: familyOf(name),
    hint: hintFor(name),
  }));
}

/** "label-custom-success" → "label-custom"; null when no trailing -segment to group. */
function familyOf(cls) {
  const m = /^(.+)-[a-zA-Z0-9][\w-]*$/.exec(cls);
  return m ? m[1] : null;
}

/** Cheap semantic hint for the conventions.md narrative. */
function hintFor(cls) {
  if (/label/i.test(cls)) return "status/field label";
  if (/well|panel|card/i.test(cls)) return "container/panel";
  if (/btn|button/i.test(cls)) return "button";
  if (/active|selected|current/i.test(cls)) return "state";
  return null;
}

// ---------- :deep() corpus ----------

/** A selector that targets a UI library's scoped internals is the reusable "how to style this
 *  library" idiom. Element Plus (.el-), Vuetify (.v-), Naive UI (.n-), Ant Design Vue (.ant-),
 *  View UI (.ivu-). Anything else (a project's own .inner/.card) is component-specific. */
function isLibraryInternal(selector) {
  return /(^|\s|,)(\.)?(el|v|n|ant|ivu)-[a-z0-9]/i.test(selector);
}

/** Merge EVERY :deep()/::v-deep() block across all SFC styles into one corpus, grouped by
 *  normalized selector with majority-vote dedup (mirrors the Angular ::ng-deep extractor's
 *  collapse logic: a single outlier block must not win over the team's dominant variant). */
function extractDeepCorpus(files) {
  const variants = new Map(); // normalized selector -> Map(canonical -> { count, block, source })
  for (const f of files) {
    for (const style of extractStyles(f.src)) {
      for (const block of extractDeepBlocks(style.body)) {
        const key = block.selector.replace(/\s+/g, " ").trim();
        if (!key) continue;
        let byBlock = variants.get(key);
        if (!byBlock) {
          byBlock = new Map();
          variants.set(key, byBlock);
        }
        const canon = semanticCanon(block.block);
        if (!byBlock.has(canon)) {
          byBlock.set(canon, { count: 0, block: block.block, source: toRelPath(f.path) });
        }
        byBlock.get(canon).count += 1;
      }
    }
  }

  const corpus = [];
  for (const [key, byBlock] of variants) {
    let best = null;
    for (const [canon, meta] of byBlock) {
      if (!best || meta.count > best.count) best = meta;
    }
    corpus.push({
      selector: key,
      block: best.block,
      source: best.source,
      reusable: isLibraryInternal(key),
    });
  }
  return collapseIdenticalCorpus(corpus);
}

/** Canonical body for dedup voting: collapse whitespace, lowercase hex colors. */
function semanticCanon(block) {
  return block.replace(/\s+/g, " ").replace(/#[0-9a-fA-F]{3,8}\b/g, (hex) => hex.toLowerCase());
}

const STATE_PSEUDO = /::?(?:hover|focus|active|visited|disabled|checked|first-child|last-child|nth-child(?:\([^)]*\))?|not\([^)]*\)|before|after)\b/g;

function stripStatePseudo(selector) {
  return String(selector).replace(STATE_PSEUDO, "").replace(/\s+/g, " ").trim();
}

/** Collapse entries that are pseudo-class variants of the SAME rule with an IDENTICAL body. */
function collapseIdenticalCorpus(corpus) {
  const groups = new Map();
  for (const c of corpus) {
    const base = stripStatePseudo(c.selector);
    const key = `${base}§${semanticCanon(c.block)}`;
    let g = groups.get(key);
    if (!g) {
      g = { block: c.block, source: c.source, reusable: c.reusable, selectors: new Set() };
      groups.set(key, g);
    }
    g.selectors.add(c.selector);
  }
  const out = [];
  for (const g of groups.values()) {
    out.push({
      selector: [...g.selectors].join(", "),
      block: g.block,
      source: g.source,
      reusable: g.reusable,
    });
  }
  return out;
}

/** Extract :deep(selector) / ::v-deep(selector) blocks with balanced parens + braces. Handles
 *  the common forms: `:deep(.el-x) { … }`, `:deep(.el-x) .child { … }`, and a scoped wrapper
 *  prefix (`.card :deep(.inner) { … }` — the wrapper is dropped, the deep target is kept). */
function extractDeepBlocks(src) {
  const clean = src.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/\/\/.*$/gm, " ");
  const out = [];
  const re = /::v-deep\s*\(|:deep\s*\(/g;
  let m;
  while ((m = re.exec(clean)) !== null) {
    const parenOpen = clean.indexOf("(", m.index);
    if (parenOpen === -1) continue;
    let pd = 0;
    let parenClose = -1;
    for (let i = parenOpen; i < clean.length; i++) {
      if (clean[i] === "(") pd++;
      else if (clean[i] === ")") { pd--; if (pd === 0) { parenClose = i; break; } }
    }
    if (parenClose === -1) continue;
    const selector = clean.slice(parenOpen + 1, parenClose).trim();
    const braceOpen = clean.indexOf("{", parenClose);
    if (braceOpen === -1) continue;
    const rest = clean.slice(parenClose + 1, braceOpen).trim();
    let depth = 0;
    let close = -1;
    for (let i = braceOpen; i < clean.length; i++) {
      if (clean[i] === "{") depth++;
      else if (clean[i] === "}") { depth--; if (depth === 0) { close = i; break; } }
    }
    if (close === -1) continue;
    const body = clean.slice(braceOpen + 1, close).trim();
    const head = (selector + (rest ? " " + rest : "")).replace(/\s+/g, " ").trim();
    out.push({
      selector: head,
      block: `:deep(${selector})${rest ? " " + rest : ""} { ${body} }`,
    });
  }
  return out;
}

// ---------- component anatomy ----------

/** Recurring SFC structure so the agent reproduces it: script setup, scoped styles, style lang,
 *  and the UI library's table/pagination components. */
function extractAnatomy(files, tailwind) {
  const templates = files.map((f) => extractTemplate(f.src)).join("\n");
  const srcs = files.map((f) => f.src).join("\n");
  const styles = files.flatMap((f) => extractStyles(f.src));

  const scriptSetup = /<script\s+setup/i.test(srcs);
  const styleScoped = styles.some((s) => /\bscoped\b/.test(s.attrs));
  const langMatch = /<style\b[^>]*\blang\s*=\s*["']([^"']+)["']/i.exec(srcs);
  const tableTag = pick(/<(el-table|v-data-table|n-data-table|a-table|t-table)\b/i, templates);
  const pagination = /<(el-pagination|v-pagination|n-pagination|a-pagination|t-pagination)\b/i.test(templates);

  return { scriptSetup, styleScoped, styleLang: langMatch?.[1] ?? null, tableTag, pagination, tailwind };
}

function pick(re, src) {
  const m = re.exec(src);
  return m ? m[1] : null;
}

// ---------- naming ----------

/** Event-handler naming (from @click/@change/@input="…") + component file casing. */
function extractNaming(files) {
  const counts = new Map();
  for (const f of files) {
    const tpl = extractTemplate(f.src);
    for (const m of tpl.matchAll(/@(\w+)(?:\.\w+)*\s*=\s*["'](\w+)/g)) {
      const handler = m[2];
      if (!/^(on[A-Z]|handle[A-Z]|[a-z][a-zA-Z0-9]*)$/.test(handler)) continue; // skip inline arrows / expressions
      counts.set(handler, (counts.get(handler) ?? 0) + 1);
    }
  }
  const top = [...counts.entries()].sort((a, b) => b[1] - a[1]);
  const eventNaming = top.length
    ? `@event="handler" — dominant handler: "${top[0][0]}" (${top[0][1]}×)`
    : null;

  const componentCase = detectComponentCase(files.map((f) => f.path));
  return { componentCase, eventNaming };
}

/** PascalCase vs kebab-case from .vue filenames (first char upper = PascalCase). */
function detectComponentCase(paths) {
  if (!paths.length) return null;
  const upper = paths.filter((p) => {
    const base = p.split(/[\\/]/).pop().replace(/\.vue$/, "");
    return /^[A-Z]/.test(base);
  }).length;
  return upper >= paths.length / 2 ? "PascalCase" : "kebab-case";
}

// ---------- helpers ----------

function readFileSyncSafe(p) {
  try { return readFileSync(p, "utf8"); } catch { return ""; }
}

function toRelPath(p) {
  const parts = p.split(/[\\/]/);
  return parts.slice(parts.length - 2).join("/");
}

/**
 * Render the agent-facing narrative profile (conventions.md) from deterministic facts.
 * Deterministic template — the agent MAY enrich it during a slice, but the baseline is written
 * here. Vue-native throughout: no ::ng-deep, no Angular event syntax, no | translate note
 * phrased as an Angular idiom.
 */
export function renderConventionsMd(conventions, frameworkLabel = "") {
  const { classVocabulary = [], deepCorpus = [], componentAnatomy = {}, naming = {} } = conventions ?? {};
  const L = [];
  L.push("<!-- Generated by SliceUI — codebase conventions. Regenerate with `sliceui init`. -->");
  L.push("");
  L.push("# Project Conventions" + (frameworkLabel ? ` — ${frameworkLabel}` : ""));
  L.push("");
  L.push("How THIS codebase writes Vue. Follow these before any framework defaults. The source of");
  L.push("truth for design is the transcript; the source of truth for idiom is this file.");
  L.push("");

  // --- SFC anatomy ---
  L.push("## SFC anatomy");
  L.push("");
  const a = componentAnatomy;
  L.push(a.scriptSetup
    ? "- `<script setup lang=\"ts\">` — Composition API (defineProps/defineEmits, ref/computed). No Options API `data()`/`methods`."
    : "- Script block: match the project's dominant style (options or composition) — not enforced here.");
  L.push(a.styleScoped
    ? `- \`<style scoped${a.styleLang ? ` lang="${a.styleLang}"` : ""}>\` — styles are component-scoped.`
    : "- Styles: not scoped by convention here — check the sample components.");
  if (a.tailwind) {
    L.push("- Tailwind: compose the project's utility classes (from its `@theme` tokens) — do NOT invent new CSS classes.");
  }
  if (a.tableTag) L.push(`- Table: use \`<${a.tableTag}>\` with the library's data/columns binding, wired client-side only (mock).`);
  if (a.pagination) L.push("- Pagination: use the library's pagination component bound to the table's own paging state (mock).");
  L.push("");

  // --- reusable classes ---
  L.push("## Reusable classes (reuse, don't invent)");
  if (a.tailwind) {
    L.push("");
    L.push("_(Tailwind project — there is no custom class vocabulary; compose utilities instead.)_");
  } else {
    const labels = classVocabulary.filter((x) => x.hint === "status/field label");
    const others = classVocabulary.filter((x) => x.hint !== "status/field label").slice(0, 20);
    if (!classVocabulary.length) {
      L.push("");
      L.push("_(none detected — this project has little template reuse; follow the transcript's classes.)_");
    } else {
      L.push("");
      L.push("Common classes seen across templates (highest frequency first):");
      L.push("");
      L.push("```");
      L.push(others.map((x) => `  ${x.name}${x.family ? `   (family: ${x.family})` : ""}`).join("\n"));
      L.push("```");
    }
    if (labels.length) {
      L.push("");
      L.push("Status/field labels are a deliberate taxonomy — use the EXACT family member, never");
      L.push("invent a new one:");
      L.push("");
      L.push("```");
      L.push(labels.map((x) => `  ${x.name}`).join("\n"));
      L.push("```");
    }
  }
  L.push("");

  // --- :deep() corpus ---
  L.push("## :deep() corpus (copy verbatim & complete)");
  const reusable = deepCorpus.filter((c) => c.reusable);
  const specific = deepCorpus.filter((c) => !c.reusable);
  if (!deepCorpus.length) {
    L.push("");
    L.push("_(none detected.)_");
  } else {
    L.push("");
    L.push("This project restyles child/library component internals with `:deep(selector)` inside");
    L.push("`<style scoped>`. **Only copy the REUSABLE blocks below** when the matching capability");
    L.push("is in play. A dropped reusable block = a lost design effect (hover, open-state, status");
    L.push("colors, table radius).");
    L.push("");
    if (reusable.length) {
      L.push("### Reusable (copy when the capability is in play)");
      L.push("");
      L.push("```scss");
      for (const c of reusable) L.push(c.block);
      L.push("```");
    }
    if (specific.length) {
      L.push("");
      L.push("### Component-specific (skip unless your slice matches this exact context)");
      L.push("");
      L.push("These target a project-specific class (not a library internal), so they belong to ONE");
      L.push("slice's context. Do NOT copy them into an unrelated page.");
      L.push("");
      L.push("```scss");
      for (const c of specific) L.push(`/* source: ${c.source} */\n${c.block}`);
      L.push("```");
    }
  }
  L.push("");

  // --- naming ---
  L.push("## Naming");
  L.push("");
  if (naming.componentCase) L.push(`- Component files: \`${naming.componentCase}\`.`);
  if (naming.eventNaming) L.push(`- Event handlers: \`${naming.eventNaming}\`.`);
  L.push("");
  L.push("## Always literal — NO i18n wrapper");
  L.push("");
  L.push("SliceUI emits mock/placeholder code, not production i18n. **Every string is literal text**");
  L.push("(template + script). Never add `$t(...)`, vue-i18n keys, or dictionary lookups — even if");
  L.push("this codebase's own components use them. Slicing deliberately deviates from the codebase");
  L.push("on this one point.");
  L.push("");

  return L.join("\n");
}
